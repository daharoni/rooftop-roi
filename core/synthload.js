const DAYS = [31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31];
const NO_DST = new Set(["America/Phoenix", "Pacific/Honolulu"]);
const pad2 = (n) => String(n).padStart(2, "0");

/**
 * A validation failure written for a homeowner.  Same convention as LoadFileError:
 * `message` is for logs, `userMessage` is a sentence the UI can show as-is.
 */
export class SynthLoadError extends Error {
  constructor(message, { code = "invalid", userMessage } = {}) {
    super(message);
    this.name = "SynthLoadError";
    this.code = code;
    this.userMessage = userMessage || "Those bills could not be used. Check the twelve numbers and try again.";
  }
}

function checkMonthly(monthlyKwh) {
  if (!Array.isArray(monthlyKwh) && !ArrayBuffer.isView(monthlyKwh)) {
    throw new SynthLoadError("monthlyKwh must be an array of 12 numbers", {
      code: "not-12", userMessage: "Please enter one number for each of the twelve months." });
  }
  if (monthlyKwh.length !== 12) {
    throw new SynthLoadError("monthlyKwh has " + monthlyKwh.length + " entries, need 12", {
      code: "not-12", userMessage: "Please enter one number for each of the twelve months." });
  }
  let total = 0;
  for (let m = 0; m < 12; m++) {
    const v = monthlyKwh[m];
    if (typeof v !== "number" || !Number.isFinite(v)) {
      throw new SynthLoadError("monthlyKwh[" + m + "] is not a finite number", {
        code: "not-number", userMessage: "One of the months is not a number. Use digits only, for example 640." });
    }
    if (v < 0) {
      throw new SynthLoadError("monthlyKwh[" + m + "] is negative", {
        code: "negative", userMessage: "A month's usage cannot be negative. If your bill shows a credit, enter 0 for that month." });
    }
    total += v;
  }
  if (!(total > 0)) {
    throw new SynthLoadError("monthlyKwh is all zero", {
      code: "all-zero", userMessage: "All twelve months are zero, so there is nothing to model. Enter the kWh from your bills." });
  }
}

/** "YYYY-MM" of the month before `now`, the last complete one. */
function lastCompleteMonth(now) {
  const y = now.getUTCFullYear(), m = now.getUTCMonth();   // m is 0-based: this month
  const py = m === 0 ? y - 1 : y, pm = m === 0 ? 12 : m;
  return py + "-" + pad2(pm);
}

/**
 * Turn twelve monthly totals into an hourly LoadSet.
 *
 * `monthlyKwh[0]` is January, whichever months the span covers: the twelve months
 * run from (endMonth - 11) to endMonth and each takes the entry of its calendar
 * month.
 */
export function synthesize({ monthlyKwh, tz = "America/Los_Angeles", endMonth, utilityId = null } = {}) {
  checkMonthly(monthlyKwh);
  const end = endMonth || lastCompleteMonth(new Date());
  if (!/^\d{4}-(0[1-9]|1[0-2])$/.test(end)) {
    throw new SynthLoadError("endMonth must look like YYYY-MM, got " + end, {
      code: "bad-month", userMessage: "The last month needs to be a year and month, such as 2026-08." });
  }
  const endY = +end.slice(0, 4), endM = +end.slice(5, 7);          // endM 1-12
  const observesDst = !NO_DST.has(tz);

  const ts = [], vals = [];
  const monthTotals = new Array(12).fill(0);
  let spanStart = null, spanEnd = null;

  for (let k = 11; k >= 0; k--) {
    // k months before endMonth
    let idx = endM - 1 - k, y = endY;
    while (idx < 0) { idx += 12; y--; }
    const cal = idx;                                               // 0-11 calendar month
    const dim = cal === 1 && ((y % 4 === 0 && y % 100 !== 0) || y % 400 === 0) ? 29 : DAYS[cal];
    const springDay = observesDst && cal === 2 ? +GBI.dstStartDate(y).slice(8, 10) : 0;
    const fallDay = observesDst && cal === 10 ? +GBI.dstEndDate(y).slice(8, 10) : 0;

    const start = ts.length;
    let sumW = 0;
    for (let d = 1; d <= dim; d++) {
      const dow = new Date(Date.UTC(y, cal, d)).getUTCDay();
      const weekend = dow === 0 || dow === 6;
      const prof = weekend ? WEEKEND[cal] : WEEKDAY[cal];
      const dayW = weekend ? WEEKEND_RATIO[cal] : 1;
      const dkey = y + "-" + pad2(cal + 1) + "-" + pad2(d);
      for (let h = 0; h < 24; h++) {
        if (d === springDay && h === 1) continue;                  // the label greenbutton.js drops that day
        const w = dayW * prof[h] * (d === fallDay && h === 1 ? 2 : 1);
        ts.push(dkey + "T" + pad2(h) + ":00");
        vals.push(w); sumW += w;
      }
    }
    // Scale this month's weights so the slots add up to the bill.
    const scale = monthlyKwh[cal] / sumW;
    for (let i = start; i < ts.length; i++) vals[i] *= scale;
    monthTotals[cal] = monthlyKwh[cal];
    if (k === 11) spanStart = ts[start];
    spanEnd = ts[ts.length - 1];
  }

  const kwh = Float64Array.from(vals);
  let totalKwh = 0;
  for (let i = 0; i < kwh.length; i++) totalKwh += kwh[i];

  return {
    meta: {
      source: "synthetic", tz, start: spanStart, end: spanEnd,
      nHours: kwh.length, totalKwh, intervalMinutes: 60, gapsFilled: [],
      utilityHint: utilityId || null,
      notes: [
        "Built from your twelve monthly bills, not from meter readings. Each month's total is exact; the hour-by-hour pattern is a typical home's.",
        "The typical pattern comes from one Southern California home with its electric car removed, so a home with big air-conditioning use, an EV or a pool will differ.",
        "Holidays are treated as ordinary weekdays.",
      ],
      monthlyKwh: Array.from(monthlyKwh),
    },
    ts, kwh, exportKwh: null,
  };
}

/**
 * Twelve monthly totals (Jan..Dec) from one annual figure, using the same
 * seasonal pattern the hourly shapes were built from.  Sums to `annualKwh`.
 */
export function seasonalSplit(annualKwh) {
  if (typeof annualKwh !== "number" || !Number.isFinite(annualKwh) || annualKwh <= 0) {
    throw new SynthLoadError("annualKwh must be a positive number", {
      code: "bad-annual", userMessage: "Enter your yearly usage in kWh as a number above zero, for example 7200." });
  }
  let t = 0;
  for (const s of MONTH_SHARE) t += s;
  return MONTH_SHARE.map((s) => annualKwh * s / t);
}

export default { synthesize, seasonalSplit, SynthLoadError };
