/* =============================================================================
 * core/synthload.js - build a LoadSet from twelve monthly bills.
 *
 * Pure ES module, no network, runs in the browser and in Node 24.
 *
 * Why: a household with no Green Button file still has a bill every month.  We
 * can spread each month's kWh over its hours with a typical home's daily shape.
 * The result is a LoadSet the engine cannot tell from a parsed one (same `ts`
 * strings, same DST days, Float64Array kwh, no export), flagged by
 * `meta.source: "synthetic"` so the UI can say how much less certain it is.
 *
 * How the shape is chosen: for each calendar month there is a weekday and a
 * weekend 24-hour profile (each sums to 1) plus a weekend-day to weekday-day
 * energy ratio.  A month's kWh is split across its days by that ratio (calendar
 * weekdays vs Saturdays and Sundays; holidays count as weekdays, we do not guess)
 * and each day's share across its hours by the profile.  Month totals are exact.
 *
 * DST follows core/greenbutton.js: the spring-forward day has 23 slots (the parsers
 * leave out the 01:00 label, see tests/greenbutton.test.mjs and the demo files), the
 * fall-back day has 24 slots and its 01:00 slot stands for two real hours, so it
 * carries double weight.  US rules; zones that do not observe DST get none.
 *
 * Limits are in docs/synthetic-load.md: the shapes come from ONE real home
 * (the demo household, Agoura Hills) with its EV removed, so there is no
 * special-case treatment of air-conditioning-heavy inland homes, EVs or pools.
 * =========================================================================== */
